//! `kage-models` - build kage's curated provider/model catalog.
//!
//! kage needs one document describing every provider it supports and
//! every tool-calling model each serves. No single upstream publishes
//! that. models.dev covers most providers but carries nothing worth
//! publishing for Command Code, and its Kenari entry lists the wider
//! pay-as-you-go catalog rather than what the subscription plans cover.
//!
//! This crate reads the five sources that do describe it between them
//! and writes two kinds of file:
//!
//! * `catalog/generated/<provider>.toml`, the upstream-published data,
//!   rewritten on every run and split across numbered shards past a
//!   threshold so a diff stays readable.
//! * `catalog/curated/<provider>.toml`, the one field no upstream
//!   publishes, kept by hand.
//!
//! `bundle` turns those files into the single models.dev-shaped
//! document kage's runtime fetches, and copies the committed
//! `static/_redirects` in beside it so the catalog also answers at the
//! site root. The JSON is a packaging step, not a translation: kage's
//! existing parser reads it unchanged.
//!
//! Subcommands:
//!
//! * `generate`: fetch every upstream and rewrite the catalog files.
//! * `check`: do not write; fail when the committed files are out of
//!   date with the upstreams. The CI drift gate.
//! * `bundle`: print the document kage fetches, for publishing.
//!
//! Every upstream URL can be overridden with `--*-url`, and a `file://`
//! URL reads a local file, so the whole pipeline runs offline against
//! the fixtures in `tests/fixtures/`.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use clap::{Parser, Subcommand};
use kage_models::{build, catalog::CuratedProvider, fetch, layout, sources};

#[derive(Parser, Debug)]
#[command(version, about, long_about = None)]
struct Cli {
    #[command(subcommand)]
    command: Command,
}

/// The five upstream URLs, shared by `generate` and `check`.
#[derive(clap::Args, Debug, Clone)]
#[expect(clippy::struct_field_names, reason = "every field is an upstream URL")]
struct Urls {
    /// Override the models.dev catalog URL.
    #[arg(long, default_value = sources::MODELS_DEV_URL)]
    models_dev_url: String,
    /// Override Kenari's model list URL.
    #[arg(long, default_value = sources::KENARI_MODELS_URL)]
    kenari_models_url: String,
    /// Override Kenari's subscription plans URL.
    #[arg(long, default_value = sources::KENARI_PLANS_URL)]
    kenari_plans_url: String,
    /// Override Command Code's model list URL.
    #[arg(long, default_value = sources::COMMAND_CODE_MODELS_URL)]
    command_code_models_url: String,
    /// Override the `command-code` CLI catalog URL.
    #[arg(long, default_value = sources::COMMAND_CODE_CLI_CATALOG_URL)]
    command_code_cli_url: String,
}

#[derive(Subcommand, Debug)]
enum Command {
    /// Fetch every upstream and rewrite the catalog files.
    Generate(Urls),
    /// Fail when the committed files are out of date with the upstreams
    /// (the CI drift gate).
    Check(Urls),
    /// Print the bundled document kage's runtime fetches.
    Bundle,
}

fn main() -> ExitCode {
    let cli = Cli::parse();
    let result = match &cli.command {
        Command::Generate(urls) => generate(urls, false),
        Command::Check(urls) => generate(urls, true),
        Command::Bundle => bundle(),
    };
    match result {
        Ok(summary) => {
            eprintln!("kage-models: {summary}");
            ExitCode::SUCCESS
        }
        Err(e) => {
            eprintln!("kage-models: {e}");
            ExitCode::from(1)
        }
    }
}

/// Read every upstream, rewrite the catalog files, or diff against them.
fn generate(urls: &Urls, check: bool) -> Result<String, String> {
    let curation = read_curation()?;
    let built = build::build(&fetch_all(urls)?, &curation)?;

    let mut written: Vec<(PathBuf, String)> = Vec::new();
    for provider in &built.providers {
        // Split before rendering: a provider past the threshold becomes
        // numbered shards, so a 318-model provider does not land as one
        // unreadable diff.
        let bodies: Vec<String> = layout::shards(&provider.generated)
            .iter()
            .map(|shard| {
                let header = format!(
                    "# @generated by `cargo run -p kage-models -- generate`.\n\
                     # Upstream-published data for {}. Do not edit by hand: the fields\n\
                     # no upstream publishes live in catalog/curated/{}.toml.\n\n",
                    provider.provider_id, provider.provider_id
                );
                toml::to_string_pretty(shard)
                    .map(|body| format!("{header}{body}"))
                    .map_err(|e| format!("render {}: {e}", provider.provider_id))
            })
            .collect::<Result<Vec<_>, _>>()?;
        let paths = layout::generated_paths(&provider.provider_id, bodies.len());
        written.extend(paths.into_iter().zip(bodies));

        // Curation is written only when it has content, so an empty
        // curated file never appears in the tree.
        if !provider.curated.is_empty() {
            let body = toml::to_string_pretty(&provider.curated)
                .map_err(|e| format!("render curated/{}: {e}", provider.provider_id))?;
            written.push((layout::curated_path(&provider.provider_id), body));
        }
    }

    if check {
        let stale: Vec<&Path> = written
            .iter()
            .filter(|(path, body)| {
                !matches!(std::fs::read_to_string(path), Ok(on_disk) if on_disk == *body)
            })
            .map(|(path, _)| path.as_path())
            .collect();
        if !stale.is_empty() {
            let names: Vec<String> = stale.iter().map(|p| p.display().to_string()).collect();
            return Err(format!(
                "{} file(s) out of date with the upstreams ({}); run `cargo run -p kage-models -- generate`",
                stale.len(),
                names.join(", ")
            ));
        }
        return Ok(format!(
            "up to date ({} models, {} providers)",
            built.models,
            built.providers.len()
        ));
    }

    for (path, body) in &written {
        if let Some(dir) = path.parent() {
            std::fs::create_dir_all(dir).map_err(|e| format!("create {}: {e}", dir.display()))?;
        }
        kage_core::fsutil::atomic_write(path, body.as_bytes())
            .map_err(|e| format!("write {}: {e}", path.display()))?;
    }
    // Drop files the run no longer produces, so a shrinking or
    // un-sharding provider leaves no stale file to be concatenated back
    // in on the next read.
    let keep: Vec<PathBuf> = written.iter().map(|(p, _)| p.clone()).collect();
    layout::prune_stale(&keep)?;

    let mut warnings = String::new();
    for warning in &built.warnings {
        let _ = writeln!(warnings, "kage-models: warning: {warning}");
    }
    Ok(format!(
        "wrote {} ({} models, {} providers)\n{warnings}",
        layout::catalog_dir().display(),
        built.models,
        built.providers.len()
    ))
}

/// Print the bundled document, and copy the routing config beside it.
///
/// The routing file is committed under `static/` and copied into the
/// deploy directory here, because `public/` is gitignored while this
/// one is config worth reviewing. The deploy directory is created here
/// too, so `bundle` works on its own; the workflow still has to create it
/// before the shell opens `> public/models.json`, which happens before
/// this runs.
fn bundle() -> Result<String, String> {
    let body = layout::bundle()?;
    println!("{body}");
    let redirects = layout::redirects_path();
    let rules = std::fs::read_to_string(&redirects)
        .map_err(|e| format!("read {}: {e}", redirects.display()))?;
    let public = layout::public_dir();
    std::fs::create_dir_all(&public).map_err(|e| format!("create {}: {e}", public.display()))?;
    std::fs::write(public.join("_redirects"), &rules)
        .map_err(|e| format!("write public/_redirects: {e}"))?;
    Ok(format!("{} bytes", body.len()))
}

/// The committed curation, one entry per provider file that holds any.
fn read_curation() -> Result<build::Curated, String> {
    let mut curation = build::Curated::default();
    let dir = layout::catalog_dir().join("curated");
    let Ok(entries) = std::fs::read_dir(&dir) else {
        return Ok(curation);
    };
    for entry in entries.filter_map(Result::ok) {
        let path = entry.path();
        if path.extension().is_none_or(|ext| ext != "toml") {
            continue;
        }
        let Some(stem) = path.file_stem().and_then(|s| s.to_str()) else {
            continue;
        };
        let body =
            std::fs::read_to_string(&path).map_err(|e| format!("read {}: {e}", path.display()))?;
        let parsed: CuratedProvider =
            toml::from_str(&body).map_err(|e| format!("parse {}: {e}", path.display()))?;
        curation.insert(stem.to_owned(), parsed);
    }
    Ok(curation)
}

/// Read all five upstreams.
///
/// # Errors
///
/// Any body fails to fetch.
fn fetch_all(urls: &Urls) -> Result<build::Inputs, String> {
    let bodies: Vec<Result<String, String>> = vec![
        fetch::fetch(&urls.models_dev_url),
        fetch::fetch(&urls.kenari_models_url),
        fetch::fetch(&urls.kenari_plans_url),
        fetch::fetch(&urls.command_code_models_url),
        fetch::fetch(&urls.command_code_cli_url),
    ];
    let mut bodies = bodies.into_iter();
    let mut take = |what: &str| -> Result<String, String> {
        bodies
            .next()
            .ok_or_else(|| format!("no body for {what}"))?
            .map_err(|e| format!("{what}: {e}"))
    };
    Ok(build::Inputs {
        models_dev: take("models.dev")?,
        kenari_models: take("kenari models")?,
        kenari_plans: take("kenari plans")?,
        command_code_models: take("command code models")?,
        command_code_cli: take("command code cli catalog")?,
    })
}
